"""The name index of the connector surface, ``docs/sdk-names.md``: every
exported name with the meaning its own documentation gives it, generated by
``ci/sdk_names.py`` and held here to the code and to the frozen name lists
(``tests/test_sdk.py``, ``tests/test_testing_kit.py``)."""

from __future__ import annotations

import re
import subprocess
import sys

from .conftest import REPO
from .test_sdk import JENKINS_TOOLKIT, PUBLIC_NAMES, ROBOT_TOOLKIT
from .test_testing_kit import KIT_NAMES

INDEX = REPO / "docs" / "sdk-names.md"
#: The stand-in's names, frozen here: what ``runcomposer.testing.jenkins`` exports.
JENKINS_KIT = {"Build", "FakeJenkins", "QueueItem", "Seen"}


def listed() -> dict[str, set[str]]:
    sections: dict[str, set[str]] = {}
    current = ""
    for line in INDEX.read_text(encoding="utf-8").splitlines():
        heading = re.match(r"^## `([\w.]+)`$", line)
        if heading:
            current = heading.group(1)
            sections[current] = set()
            continue
        row = re.match(r"^\| `(\w+)` \| (.+) \|$", line)
        if row and current:
            assert row.group(2).strip(), f"{current}.{row.group(1)} has no meaning in the index"
            sections[current].add(row.group(1))
    return sections


def test_the_index_is_what_the_generator_writes_from_the_code():
    done = subprocess.run(
        [sys.executable, str(REPO / "ci" / "sdk_names.py"), "--check"],
        capture_output=True, text=True, timeout=120,
    )
    assert done.returncode == 0, done.stdout + done.stderr


def test_the_index_lists_exactly_the_frozen_surface():
    assert listed() == {
        "runcomposer.sdk": PUBLIC_NAMES,
        "runcomposer.sdk.robot": ROBOT_TOOLKIT,
        "runcomposer.sdk.jenkins": JENKINS_TOOLKIT,
        "runcomposer.testing": KIT_NAMES,
        "runcomposer.testing.jenkins": JENKINS_KIT,
    }


def test_the_stand_in_exports_exactly_its_frozen_names():
    import runcomposer.testing.jenkins as stand_in

    assert set(stand_in.__all__) == JENKINS_KIT


def test_the_guide_points_at_the_index():
    guide = (REPO / "docs" / "connectors.md").read_text(encoding="utf-8")
    assert "sdk-names.md" in guide


def test_every_count_of_the_store_protocol_in_the_docs_is_the_codes():
    """Where a document says how many members the ``RunStore`` protocol has,
    the number is ``contract_members(RunStore)``'s — so it cannot drift."""
    import re

    from runcomposer.sdk import RunStore, contract_members

    actual = len(contract_members(RunStore))
    counted = re.compile(
        r"RunStore`?\s+protocol[^.\n]{0,40}?\b(\d+)\b|protocol has (\d+) members|(\d+) members of the `?RunStore",
        re.I,
    )
    found = []
    for name in ("README.md", "ADOPTING.md", "DESIGN.md", "CHANGELOG.md", "CONTRIBUTING.md", "docs/connectors.md"):
        path = REPO / name
        if path.is_file():
            for match in counted.finditer(path.read_text(encoding="utf-8")):
                found.append((name, int(next(group for group in match.groups() if group))))
    assert found, "the guide states the count"
    assert [entry for entry in found if entry[1] != actual] == []
