#!/usr/bin/env python3
"""Write (or check) docs/sdk-names.md: every exported name of the connector
surface with the one-line meaning its own documentation gives it.

    python ci/sdk_names.py           # rewrite docs/sdk-names.md
    python ci/sdk_names.py --check   # exit 1 when the file is not what it would write

The modules are ``runcomposer.sdk``, its toolkits ``runcomposer.sdk.robot``
and ``runcomposer.sdk.jenkins``, and the conformance kit
``runcomposer.testing`` and ``runcomposer.testing.jenkins`` — the names in
their ``__all__``. A name's meaning is the first sentence of its docstring;
a constant, which has no docstring, is described by the ``#:`` comment above
its definition. A name with neither is an error: every exported name says
what it is.
"""

from __future__ import annotations

import importlib
import inspect
import re
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

TARGET = REPO / "docs" / "sdk-names.md"
MODULES = (
    "runcomposer.sdk",
    "runcomposer.sdk.robot",
    "runcomposer.sdk.jenkins",
    "runcomposer.testing",
    "runcomposer.testing.jenkins",
)
HEADER = """# The connector surface, name by name

Generated by `python ci/sdk_names.py` from the modules themselves — do not
edit by hand; `tests/test_sdk_names.py` fails when this file and the code
disagree. Every name exported by the connector surface is listed with the
first sentence of its own documentation (a constant: the comment above its
definition). [connectors.md](connectors.md) is the guide that explains how
they fit together; the stability promise of its §1 covers each name with the
meaning given here and in its docstring.
"""

_SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[A-Z`(*])")


def first_sentence(text: str) -> str:
    """The first sentence of a docstring or comment, on one line."""
    paragraph = inspect.cleandoc(text).split("\n\n", 1)[0]
    flat = " ".join(paragraph.split())
    return _SENTENCE_END.split(flat, 1)[0]


def comment_above(name: str) -> str | None:
    """The ``#:`` comment above ``NAME = …`` in the package's sources."""
    pattern = re.compile(rf"^((?:#:.*\n)+)(?:{re.escape(name)}\s*[:=])", re.MULTILINE)
    for path in sorted((REPO / "src" / "runcomposer").rglob("*.py")):
        match = pattern.search(path.read_text(encoding="utf-8"))
        if match:
            return " ".join(line[2:].strip() for line in match.group(1).splitlines())
    return None


def meaning(module: Any, name: str) -> str:
    value = getattr(module, name)
    if inspect.isclass(value) or inspect.isfunction(value) or inspect.ismethod(value):
        doc = inspect.getdoc(value)
        own = value.__doc__ is not None and (not inspect.isclass(value) or "__doc__" in vars(value))
        generated = bool(doc) and doc.startswith(f"{value.__name__}(")  # a dataclass's signature
        if doc and own and not generated:
            return first_sentence(doc)
        raise SystemExit(f"{module.__name__}.{name} has no docstring of its own")
    comment = comment_above(name)
    if comment:
        return first_sentence(comment)
    raise SystemExit(f"{module.__name__}.{name} has neither a docstring nor a '#:' comment")


def render() -> str:
    lines = [HEADER]
    for module_name in MODULES:
        module = importlib.import_module(module_name)
        lines.append(f"\n## `{module_name}`\n")
        lines.append("| Name | Meaning |\n|---|---|")
        for name in sorted(module.__all__, key=str.casefold):
            text = meaning(module, name).replace("|", "\\|")
            lines.append(f"| `{name}` | {text} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"{TARGET.relative_to(REPO)} is out of date — run python ci/sdk_names.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
